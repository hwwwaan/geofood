def split_name(name):
    """등록명칭에서 품목을 떼고 앞을 지역으로 본다. 긴 품목명부터 맞춰본다."""
    for goods, months, cat, always in sorted(GOODS, key=lambda g: -len(g[0])):
        if name.endswith(goods):
            region = name[: -len(goods)]
            return region or "전국", goods, months, cat, always
    return None


def build():
    items, unmatched = [], []

    for line in AGRI_RAW.strip().splitlines():
        year, names = line.split(" ", 1)
        for name in names.split(","):
            name = name.strip()
            got = split_name(name)
            if not got:
                unmatched.append(name)
                continue
            region, goods, months, cat, always = got
            items.append({
                "id": f"a-{name}", "name": name, "region": region,
                "sido": SIDO.get(region, "확인 필요"), "goods": goods,
                "category": cat, "months": months, "alwaysAvailable": always,
                "kind": "농산물", "year": int(year), "no": None,
            })

    for chunk in SEA_RAW.strip().replace("\n", "|").split("|"):
        chunk = chunk.strip()
        if not chunk:
            continue
        no, name = chunk.split(" ", 1)
        got = split_name(name.strip())
        if not got:
            unmatched.append(name)
            continue
        region, goods, months, cat, always = got
        items.append({
            "id": f"s-{no}", "name": name.strip(), "region": region,
            "sido": SIDO.get(region, "확인 필요"), "goods": goods,
            "category": cat, "months": months, "alwaysAvailable": always,
            "kind": "수산물", "year": None, "no": int(no),
        })

    if unmatched:
        print("품목을 못 가른 것:", unmatched, file=sys.stderr)

